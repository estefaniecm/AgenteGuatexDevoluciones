    private void btnInicioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInicioActionPerformed
        try {
            String passwordDesencriptada = "";
            String passwordIngreso = this.txtPassword.getText().trim().toUpperCase();
            String passwordDefinida = GTXConfiguracionIG.parametros.getProperty("password");
            if (passwordDefinida.isEmpty()) {
                passwordDefinida = Parametros.getPassword();
            }

            if (passwordIngreso.isEmpty()) {
                lbIncorrecto.setText("* Debe ingresar la contraseña *");
            } else {
                passwordDesencriptada = new CifradoPassword().decrypt(passwordDefinida);
                if (passwordIngreso.equals(passwordDesencriptada)) {
                    jpContenedor.removeAll();
                    jpContenedor.repaint();
                    jpContenedor.revalidate();
                    btnMParams.setEnabled(true);
                    btnMServicio.setEnabled(true);
                    btnMUsuarios.setEnabled(true);
                    btnMImpresoras.setEnabled(true);
                } else {
                    lbIncorrecto.setText("* La contraseña es incorrecta *");
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }

    }//GEN-LAST:event_btnInicioActionPerformed

