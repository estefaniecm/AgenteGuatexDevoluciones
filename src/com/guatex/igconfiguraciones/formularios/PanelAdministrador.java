    private void cambiarbtnColores(JButton selected) {
        if (selectedButton != null) {
            // Restaurar el color del botón previamente seleccionado
            selectedButton.setBackground(null);
        }
        // Establecer el nuevo botón seleccionado
        selectedButton = selected;
        this.jpContenedor.setVisible(true);
        selectedButton.setBackground(new Color(238, 238, 238));
    }

