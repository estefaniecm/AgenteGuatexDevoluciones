    // Método que realiza la conexión al API en segundo plano
    private class ConexionAPI extends SwingWorker<Void, Void> {

        @Override
        protected Void doInBackground() throws Exception {
            String conexion = new G_ConsultasBD().pruebaConexion();
            labelConexion.setVisible(false);
            if (conexion.equals("OK")) {
                ArchivoLogs.getInstance().grabaLogFileAdministrador("------ Prueba de conexión con Guatex exitosa.", false);
                JOptionPane.showMessageDialog(jPanel1, "Sí hay conexión con Guatex.", "Conexión exitosa", JOptionPane.INFORMATION_MESSAGE);
            } else {
                ArchivoLogs.getInstance().grabaLogFileAdministrador("------ Prueba de conexión con Guatex fallida.", true);
                JOptionPane.showMessageDialog(jPanel1, "No hay conexión con Guatex.", "Error de conexión", JOptionPane.ERROR_MESSAGE);
            }
            return null;
        }
    }

    private void eliminarConfiguracionAgente() {
        String input = "";
        boolean ingresoValido = false;
        while (!ingresoValido) {
            input = JOptionPane.showInputDialog(this, "¿Está seguro que desea eliminar la configuración?\n\nEscriba 'aceptar' o 'cancelar':", "Eliminar configuración - Agente Guatex", JOptionPane.QUESTION_MESSAGE);
            if ("aceptar".equalsIgnoreCase(input) || "cancelar".equalsIgnoreCase(input)) {
                ingresoValido = true;
                if ("aceptar".equalsIgnoreCase(input)) {
                    eliminacion();
                }
            } else {
                JOptionPane.showMessageDialog(this, "Por favor, escriba 'aceptar' o 'cancelar'.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }

    public void eliminacion() {
        try {
            String carpetaArchivo = Parametros.getRutaRaiz() + "SERVICIO_IMPRESION_GUATEX";
            File carpeta = new File(carpetaArchivo);
            if (carpeta.exists()) {
                if (eliminarCarpeta(carpeta)) {
                    int enterado = JOptionPane.showConfirmDialog(this,
                            "Los archivos de configuración se eliminaron correctamente.\n\nPuedes proceder a configurar nuevamente el Agente Guatex.",
                            "¡Eliminación exitosa!",
                            JOptionPane.DEFAULT_OPTION,
                            JOptionPane.INFORMATION_MESSAGE);
                    if (enterado == JOptionPane.OK_OPTION) {
                        ArchivoLogs.getInstance().grabaLogFileAdministrador("------ Eliminación de configuración.", false);
                        GTXConfiguracionIG.reinicioConfiguracionIG();
                        GTXConfiguracionIG.inicioAgenteGuatex();
                        reinicioConsulta();
                        mostrarParametros();
                    }
                }
            } else {
                System.out.println("La carpeta no existe: " + carpetaArchivo);
            }
        } catch (Exception e) {
            System.out.println("error: ");
            ArchivoLogs.getInstance().grabaLogFileAdministrador("------ Excepción - Elimina configuración - " + e.getLocalizedMessage(), true);
            e.printStackTrace();
        }

    }

    private static void reinicioConsulta() {
        if (GTXConfiguracionIG.imp != null) {
            GTXConfiguracionIG.imp.detener();
        }
        GTXConfiguracionIG.imp = new ImpresionesPendientes();
        GTXConfiguracionIG.imp.iniciar();
    }

    private boolean eliminarCarpeta(File carpeta) {
        File[] archivos = carpeta.listFiles();
        if (archivos != null) { //Verifica que la carpeta contenga archivos
            for (File archivo : archivos) {
                if (archivo.isDirectory()) {
                    // Elimina subcarpetas
                    if (!eliminarCarpeta(archivo)) {
                        return false;
                    }
                } else {
                    // Elimina archivos
                    if (!archivo.delete()) {
                        System.out.println("No se pudo eliminar el archivo: " + archivo.getAbsolutePath());
                        return false;
                    }
                }
            }
        }
        // Elimina la carpeta al estar vacía
        if (carpeta.delete()) {
            return true;
        } else {
            return false;
        }
    }

