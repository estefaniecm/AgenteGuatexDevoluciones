    /*Botón para guardar nuevos parámetros*/
    private void btnMUGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMUGuardarActionPerformed
        Parametros p = new Parametros();
        try {
            int t = Integer.parseInt(this.txtTiempo.getText().trim());
            if (t >= 1) {
                p.setTiempoEspera(t);
                if (new A_Params().guardarParametrosArchivo()) {
                    GTXConfiguracionIG.parametros = new A_Params().cargarPropiedades();
                    int respuesta = JOptionPane.showConfirmDialog(null,
                            "El tiempo de espera para la impresión de guías pendientes \nse modificó correctamente.",
                            "Tiempo modificado", JOptionPane.DEFAULT_OPTION, JOptionPane.INFORMATION_MESSAGE);
                    if (respuesta == JOptionPane.OK_OPTION || respuesta == JOptionPane.CLOSED_OPTION) {
                        ArchivoLogs.getInstance().grabaLogFileAdministrador("------ Tiempo de espera modificado [" + t + "]", false);
                        mostrarParametros();
                        reinicioConsulta();
                    }
                }
            } else {
                JOptionPane.showMessageDialog(jPanel1, "Por favor ingrese un número entero mayor o igual a 1", "Error - minutos de espera", JOptionPane.ERROR_MESSAGE);
                this.txtTiempo.setText("");
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(jPanel1, "Por favor ingrese un número entero mayor a 1", "Error - minutos de espera", JOptionPane.ERROR_MESSAGE);
            this.txtTiempo.setText("");
        }
    }//GEN-LAST:event_btnMUGuardarActionPerformed

